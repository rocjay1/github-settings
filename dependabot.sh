#!/usr/bin/env bash
# Render each repo's .github/dependabot.yml from shared conventions plus the per-repo
# entries below, and diff it against what the repo has.
# Dry run by default; pass --apply to open a PR in each repo that differs. Further
# arguments limit the run to those repos: ./dependabot.sh --apply applebridge
set -euo pipefail

apply=false
[[ "${1:-}" == "--apply" ]] && { apply=true; shift; }
only=("$@")

path=".github/dependabot.yml"
branch="sync-dependabot-config"
header="# Managed by rocjay1/github-settings (dependabot.sh). Edit it there; changes here get overwritten."

# Ecosystems per repo, one "ecosystem dir [dir...]" per line. A repo with no entry gets
# the default (github-actions at /) and is flagged; an entry with no lines opts the repo out.
ecosystems() {
  case "$1" in
    applebridge)       printf '%s\n' "github-actions /" "swift /" ;;
    # "/" covers .github/workflows; the composite action needs its own entry.
    core-infra)        printf '%s\n' "github-actions / /.github/actions/*" \
                                     "terraform /cloudflare /gcp" "uv /" ;;
    rocjay1.github.io) printf '%s\n' "github-actions /" "uv /" ;;
    simplifi-cli)      printf '%s\n' "github-actions /" "uv /" ;;
    copilot-config)    printf '%s\n' "github-actions /" ;;
    github-settings)   printf '%s\n' "github-actions /" ;;
    mac-config)        printf '%s\n' "github-actions /" ;;  # Brewfile, Ansible: not supported
    cop-rehearsal)     ;;                                    # throwaway repo
    *) return 1 ;;
  esac
}

# Extra YAML appended to one repo's ecosystem entry (ignore rules and the like).
extra() {
  case "$1:$2" in
    applebridge:swift) cat <<'EOF'
    ignore:
      # Capped in Package.swift: 1.7.2+ requires Swift 6.4. Drop once 6.4 is the floor.
      - dependency-name: "github.com/apple/swift-collections"
        versions: [">= 1.7.2"]
EOF
    ;;
  esac
}

# Shared conventions: one monthly PR across all ecosystems, a week's cooldown on new releases.
render() {
  local r=$1 spec=$2 eco dirs
  printf '%s\n' "$header" "version: 2" "" \
    "multi-ecosystem-groups:" "  monthly:" "    schedule:" '      interval: "monthly"' \
    "    commit-message:" '      prefix: "build(deps)"' "" "updates:"
  while read -r eco dirs; do
    echo "  - package-ecosystem: \"$eco\""
    if [[ "$dirs" == *" "* || "$dirs" == *"*"* ]]; then
      echo "    directories:"
      for d in $dirs; do echo "      - \"$d\""; done
    else
      echo "    directory: \"$dirs\""
    fi
    printf '%s\n' "    assignees: [\"$owner\"]" '    patterns: ["*"]' \
      '    multi-ecosystem-group: "monthly"' "    cooldown:" "      default-days: 7"
    extra "$r" "$eco"
    echo
  done <<<"$spec"
}

# Put the rendered file on $branch and open a PR if none is open. With a PR open, commit
# on top of its branch (resetting it would empty the PR and GitHub would close it);
# otherwise start the branch afresh from the default branch head.
open_pr() {
  local r=$1 content=$2 verb=$3 base head file_sha="" pr msg on_branch=""
  base=$(gh api "repos/$owner/$r" --jq .default_branch)
  pr=$(gh api "repos/$owner/$r/pulls?state=open&head=$owner:$branch" --jq '.[0].html_url // empty')
  if [[ -z "$pr" ]]; then
    head=$(gh api "repos/$owner/$r/git/ref/heads/$base" --jq .object.sha)
    if gh api "repos/$owner/$r/git/ref/heads/$branch" --silent 2>/dev/null; then
      gh api -X PATCH "repos/$owner/$r/git/refs/heads/$branch" -f sha="$head" -F force=true --silent
    else
      gh api -X POST "repos/$owner/$r/git/refs" -f ref="refs/heads/$branch" -f sha="$head" --silent
    fi
  fi
  if b64=$(gh api "repos/$owner/$r/contents/$path?ref=$branch" 2>/dev/null); then
    file_sha=$(jq -r .sha <<<"$b64")
    on_branch=$(jq -r .content <<<"$b64" | base64 -d)
  fi
  if [[ -n "$pr" && "$on_branch" == "$content" ]]; then
    echo "$r: $pr already up to date"
    return 0
  fi

  msg=$(printf '%s\n' "$verb Dependabot config from github-settings" "" \
    "Generated by rocjay1/github-settings dependabot.sh; edit it there." "" \
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
  jq -n --arg message "$msg" --arg branch "$branch" --arg sha "$file_sha" \
    --arg content "$(printf '%s\n' "$content" | base64 | tr -d '\n')" \
    '{message: $message, branch: $branch, content: $content} + (if $sha == "" then {} else {sha: $sha} end)' \
    | gh api -X PUT "repos/$owner/$r/contents/$path" --input - --silent

  if [[ -z "$pr" ]]; then
    pr=$(jq -n --arg title "$verb Dependabot config from github-settings" --arg head "$branch" --arg base "$base" \
      --arg body "$(printf '%s\n' \
        "Renders \`$path\` from the shared conventions in [rocjay1/github-settings](https://github.com/$owner/github-settings) (\`dependabot.sh\`). Change the config there, not here." \
        "" "🤖 Generated with [Claude Code](https://claude.com/claude-code)")" \
      '{title: $title, head: $head, base: $base, body: $body}' \
      | gh api -X POST "repos/$owner/$r/pulls" --input - --jq .html_url)
    echo "$r: opened $pr"
  else
    echo "$r: updated $pr"
  fi
}

owner=$(gh api user --jq .login)
changed=0
set -f  # directory globs like /.github/actions/* must stay literal
for r in $(gh repo list "$owner" --limit 500 --no-archived --source --json name --jq '.[].name'); do
  if (( ${#only[@]} )) && [[ " ${only[*]} " != *" $r "* ]]; then continue; fi
  note=""
  spec=$(ecosystems "$r") || { spec="github-actions /"; note=" (no entry in dependabot.sh; using default)"; }
  # gh prints the 404 body on stdout, so only decode when the call succeeds.
  have=""
  if b64=$(gh api -H "Cache-Control: no-cache" "repos/$owner/$r/contents/$path" --jq .content 2>/dev/null); then
    have=$(base64 -d <<<"$b64")
  fi
  alt=$(gh api "repos/$owner/$r/contents/.github/dependabot.yaml" --jq .path 2>/dev/null) || alt=""
  [[ -n "$alt" ]] && echo "$r: warning: also has .github/dependabot.yaml"

  if [[ -z "$spec" ]]; then
    if [[ -n "$have" ]]; then
      changed=$((changed + 1)); echo "$r: opted out, but has $path"
    else
      echo "$r: opted out"
    fi
    continue
  fi

  want=$(render "$r" "$spec")  # $(...) drops the trailing blank line
  if [[ "$have" == "$want" ]]; then
    echo "$r: dependabot ok"
  else
    changed=$((changed + 1))
    if [[ -z "$have" ]]; then verb="Add"; echo "$r: create $path$note"
    else verb="Sync"; echo "$r: update $path$note"; fi
    if [[ -z "$have" ]]; then
      printf '%s\n' "$want" | sed "s/^/$r:   > /"
    else
      diff <(printf '%s\n' "$have") <(printf '%s\n' "$want") | sed "s/^/$r:   /" || true
    fi
    $apply && open_pr "$r" "$want" "$verb"
  fi
done

if ! $apply && (( changed > 0 )); then
  echo; echo "Dry run: $changed repo(s) differ. Re-run with --apply to open PRs."
fi
