#!/usr/bin/env python3
"""Render each repo's .github/dependabot.yml from shared conventions plus the per-repo
entries below, and diff it against what the repo has.

Dry run by default; pass --apply to open a PR in each repo that differs, or --check to
exit 1 when any repo differs (scheduled drift check, drift.yml). Further arguments limit
the run to those repos: ./dependabot.py --apply applebridge
"""

from common import api, current_user, fetch, list_repos, open_pr, parse_args, print_diff, run

PATH = ".github/dependabot.yml"
BRANCH = "sync-dependabot-config"
HEADER = ("# Managed by rocjay1/github-settings (dependabot.py). "
          "Edit it there; changes here get overwritten.")

# Ecosystems per repo as (ecosystem, [directories]). A repo with no entry gets DEFAULT and
# is flagged; an empty list opts the repo out.
ECOSYSTEMS = {
    "applebridge": [("github-actions", ["/"]), ("swift", ["/"])],
    # "/" covers .github/workflows; the composite action needs its own entry.
    "core-infra": [("github-actions", ["/", "/.github/actions/*"]),
                   ("terraform", ["/cloudflare", "/gcp"]), ("uv", ["/"])],
    "rocjay1.github.io": [("github-actions", ["/"]), ("uv", ["/"])],
    "simplifi-cli": [("github-actions", ["/"]), ("uv", ["/"])],
    "copilot-config": [("github-actions", ["/"])],
    "github-settings": [("github-actions", ["/"])],
    "mac-config": [("github-actions", ["/"])],  # Brewfile, Ansible: not supported
    "cop-rehearsal": [],                         # throwaway repo
}
DEFAULT = [("github-actions", ["/"])]

# Extra YAML appended to one repo's ecosystem entry (ignore rules and the like).
EXTRA = {
    ("applebridge", "swift"): """\
    ignore:
      # Capped in Package.swift: 1.7.2+ requires Swift 6.4. Drop once 6.4 is the floor.
      - dependency-name: "github.com/apple/swift-collections"
        versions: [">= 1.7.2"]
""",
}


def render(owner, repo, spec):
    """Shared conventions: one monthly PR across all ecosystems, a week's cooldown on new
    releases."""
    lines = [HEADER, "version: 2", "",
             "multi-ecosystem-groups:", "  monthly:", "    schedule:", '      interval: "monthly"',
             "    commit-message:", '      prefix: "build(deps)"', "", "updates:"]
    for eco, dirs in spec:
        lines.append(f'  - package-ecosystem: "{eco}"')
        if len(dirs) > 1 or "*" in dirs[0]:
            lines.append("    directories:")
            lines += [f'      - "{d}"' for d in dirs]
        else:
            lines.append(f'    directory: "{dirs[0]}"')
        lines += [f'    assignees: ["{owner}"]', '    patterns: ["*"]',
                  '    multi-ecosystem-group: "monthly"', "    cooldown:", "      default-days: 7"]
        lines += EXTRA.get((repo, eco), "").splitlines()
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    args = parse_args(__doc__, repos=True)
    owner = current_user()
    changed = 0
    for repo in list_repos(owner, args.repos):
        note = ""
        spec = ECOSYSTEMS.get(repo)
        if spec is None:
            spec, note = DEFAULT, " (no entry in dependabot.py; using default)"
        have, _ = fetch(owner, repo, PATH)
        if api(f"repos/{owner}/{repo}/contents/.github/dependabot.yaml", missing_ok=True):
            print(f"{repo}: warning: also has .github/dependabot.yaml")

        if not spec:
            if have:
                changed += 1
                print(f"{repo}: opted out, but has {PATH}")
            else:
                print(f"{repo}: opted out")
            continue

        want = render(owner, repo, spec)
        if have == want:
            print(f"{repo}: dependabot ok")
            continue
        changed += 1
        verb = "Sync" if have else "Add"
        print(f"{repo}: {'update' if have else 'create'} {PATH}{note}")
        print_diff(repo, have, want)
        if args.apply:
            open_pr(owner, repo, PATH, BRANCH, want,
                    title=f"{verb} Dependabot config from github-settings",
                    commit_note="Generated by rocjay1/github-settings dependabot.py; edit it there.",
                    body=f"Renders `{PATH}` from the shared conventions in "
                         f"[rocjay1/github-settings](https://github.com/{owner}/github-settings) "
                         "(`dependabot.py`). Change the config there, not here.\n\n"
                         "🤖 Generated with [Claude Code](https://claude.com/claude-code)")

    if not args.apply and changed:
        print(f"\nDry run: {changed} repo(s) differ. Re-run with --apply to open PRs.")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    run(main)
